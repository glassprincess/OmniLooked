export type Language = 'en' | 'ru';

function detectLanguage(): Language {
  const preferred = typeof navigator === 'undefined' ? '' : navigator.language.toLowerCase();
  return preferred.startsWith('ru') ? 'ru' : 'en';
}

export const language: Language = detectLanguage();

const dictionary: Record<MessageKey, string> = language === 'ru' ? ru : en;

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = dictionary[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
